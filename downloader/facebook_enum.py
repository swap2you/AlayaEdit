from __future__ import annotations

import re
from collections.abc import Callable
from pathlib import Path

from playwright.sync_api import Page, sync_playwright
from rich.console import Console

console = Console()

REEL_HINT = re.compile(r"/(reel|reels|videos|watch)/", re.I)
ABS_MEDIA = re.compile(
    r"https?://(?:www\.)?facebook\.com/(?:reel/\d+|watch/?\?v=\d+|[^\"\s]+/videos/\d+)",
    re.I,
)
REEL_ID = re.compile(r"/reel/(\d+)", re.I)

# Signals we left the reels grid (stop harvesting).
END_SECTION_HINTS = (
    "photos",
    "friends",
    "people you may know",
    "manage posts",
    "about",
)


def _normalize(url: str) -> str:
    return url.split("#")[0].strip()


def reel_id_from_url(url: str) -> str | None:
    match = REEL_ID.search(url)
    return match.group(1) if match else None


def export_cookies(context, path: Path) -> Path:
    """Write Playwright cookies as Netscape cookies.txt for yt-dlp."""
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Netscape HTTP Cookie File",
        "# Generated by media-pipeline",
    ]
    for cookie in context.cookies():
        domain = cookie.get("domain") or ""
        flag = "TRUE" if domain.startswith(".") else "FALSE"
        path_val = cookie.get("path") or "/"
        secure = "TRUE" if cookie.get("secure") else "FALSE"
        expires = str(int(cookie.get("expires") or 0))
        name = cookie.get("name") or ""
        value = cookie.get("value") or ""
        if not name:
            continue
        lines.append(
            "\t".join([domain, flag, path_val, secure, expires, name, value])
        )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def _harvest_visible_reels(page: Page, seen: set[str]) -> list[str]:
    """Collect new reel/video URLs currently in the DOM."""
    found: list[str] = []

    def add(url: str) -> None:
        url = _normalize(url)
        if not url or url in seen:
            return
        if "facebook.com" not in url:
            return
        if not (REEL_HINT.search(url) or "/reel/" in url):
            return
        if "sk=reels_tab" in url or url.rstrip("/").endswith("/reels"):
            return
        # Prefer canonical /reel/<id> links
        clean = url.split("&")[0].split("?")[0]
        if clean in seen:
            return
        seen.add(url)
        seen.add(clean)
        found.append(clean if "/reel/" in clean else url.split("&")[0])

    hrefs = page.eval_on_selector_all(
        "a[href]",
        "els => els.map(e => e.href)",
    )
    for href in hrefs:
        if isinstance(href, str):
            add(href)

    for match in ABS_MEDIA.findall(page.content()):
        add(match)

    # Keep unique order, prefer /reel/ ids
    ordered: list[str] = []
    ids_seen: set[str] = set()
    for url in found:
        rid = reel_id_from_url(url)
        if rid:
            if rid in ids_seen:
                continue
            ids_seen.add(rid)
        ordered.append(url)
    return ordered


def _is_logged_in(context) -> bool:
    names = {c.get("name") for c in context.cookies()}
    return "c_user" in names


def _dismiss_login_walls(page: Page) -> None:
    """Close 'See more on Facebook' / soft login overlays when possible."""
    for sel in (
        'div[aria-label="Close"]',
        'div[aria-label="Close dialog"]',
        'div[role="button"][aria-label="Close"]',
        'div[aria-label="Dismiss"]',
    ):
        try:
            loc = page.locator(sel).first
            if loc.count():
                loc.click(timeout=1500)
                page.wait_for_timeout(500)
        except Exception:  # noqa: BLE001
            continue


def _wait_for_facebook_login(page: Page, context, timeout_sec: int = 600) -> None:
    """Pause until the user completes Facebook SSO in the headed window."""
    if _is_logged_in(context):
        _dismiss_login_walls(page)
        console.print("[green]Facebook session already logged in.[/green]")
        return

    console.print(
        "[yellow]Facebook login required to load more than the first ~10 public reels.\n"
        "Complete SSO in the opened browser (dismiss 'See more on Facebook' after login). "
        "Waiting...[/yellow]"
    )
    import time

    deadline = time.time() + timeout_sec
    while time.time() < deadline:
        if _is_logged_in(context):
            page.wait_for_timeout(2000)
            _dismiss_login_walls(page)
            # Reload reels tab so the full grid loads under the session
            page.reload(wait_until="domcontentloaded")
            page.wait_for_timeout(4000)
            _dismiss_login_walls(page)
            console.print("[green]Facebook login detected — continuing harvest.[/green]")
            return
        # Soft nudge: if login form visible, leave it for the user
        page.wait_for_timeout(2000)
    raise TimeoutError("Timed out waiting for Facebook login")


def _scroll_and_wait_for_new(
    page: Page,
    *,
    previous_unique: int,
    wait_ms: int = 2800,
    poll_ms: int = 600,
    max_wait_ms: int = 15000,
) -> int:
    """
    Scroll the reels grid (mouse wheel on grid + last-tile into view), then wait
    for lazy-loaded /reel/ ids to increase.
    """
    _dismiss_login_walls(page)

    # Focus near the reels grid and wheel several times
    try:
        first = page.locator('a[href*="/reel/"]').first
        box = first.bounding_box()
        if box:
            page.mouse.move(box["x"] + box["width"] / 2, min(box["y"] + 350, 800))
    except Exception:  # noqa: BLE001
        pass

    for _ in range(3):
        page.mouse.wheel(0, 1600)
        page.wait_for_timeout(400)

    page.evaluate(
        """() => {
            const reels = document.querySelectorAll('a[href*="/reel/"]');
            const last = reels[reels.length - 1];
            if (last) last.scrollIntoView({block: 'end', behavior: 'instant'});
            const main = document.querySelector('[role="main"]');
            if (main) main.scrollBy(0, Math.max(window.innerHeight, 900));
            window.scrollBy(0, Math.max(window.innerHeight * 0.9, 900));
        }"""
    )
    page.keyboard.press("PageDown")
    page.wait_for_timeout(wait_ms)

    def unique_count() -> int:
        return int(
            page.evaluate(
                """() => {
                  const ids = new Set();
                  for (const a of document.querySelectorAll('a[href*="/reel/"]')) {
                    const m = a.href.match(/\\/reel\\/(\\d+)/);
                    if (m) ids.add(m[1]);
                  }
                  return ids.size;
                }"""
            )
        )

    waited = wait_ms
    while waited < max_wait_ms:
        current = unique_count()
        if current > previous_unique:
            page.wait_for_timeout(1500)  # let a full batch paint
            return unique_count()
        page.mouse.wheel(0, 1000)
        page.wait_for_timeout(poll_ms)
        waited += poll_ms
    return unique_count()


def _looks_past_reels(page: Page) -> bool:
    """Heuristic: page body suggests we've left the reels grid."""
    try:
        body = page.inner_text("body").lower()
    except Exception:  # noqa: BLE001
        return False
    # Still on reels tab URL is fine; only stop on strong non-reel chrome
    # after stagnant scrolls — this is an extra signal.
    hits = sum(1 for hint in END_SECTION_HINTS if hint in body)
    reel_links = page.evaluate(
        """() => document.querySelectorAll('a[href*="/reel/"]').length"""
    )
    return hits >= 3 and reel_links == 0


def harvest_facebook_reels(
    page_url: str,
    *,
    limit: int | None = None,
    user_data_dir: str | Path = ".playwright/facebook-browse-profile",
    headed: bool = True,
    stagnant_scrolls_to_stop: int = 5,
    max_scrolls: int = 200,
    wait_after_scroll_ms: int = 2500,
    cookies_out: Path | None = None,
    on_batch: Callable[[list[str], Path | None], None] | None = None,
) -> tuple[list[str], Path | None]:
    """
    Scroll a Facebook reels tab with waits for lazy-load, optionally invoking
    on_batch(new_urls, cookies_path) after each batch so downloads can run
    incrementally. Stops when scrolling yields no new reels for several rounds.
    """
    profile = Path(user_data_dir).resolve()
    profile.mkdir(parents=True, exist_ok=True)
    all_urls: list[str] = []
    seen: set[str] = set()
    cookie_path: Path | None = None
    stagnant = 0

    with sync_playwright() as p:
        try:
            context = p.chromium.launch_persistent_context(
                user_data_dir=str(profile),
                headless=not headed,
                channel="chrome",
                args=["--disable-blink-features=AutomationControlled"],
                viewport={"width": 1280, "height": 900},
            )
        except Exception:
            context = p.chromium.launch_persistent_context(
                user_data_dir=str(profile),
                headless=not headed,
                args=["--disable-blink-features=AutomationControlled"],
                viewport={"width": 1280, "height": 900},
            )

        page = context.pages[0] if context.pages else context.new_page()
        console.print(f"[cyan]Opening Facebook reels tab:[/cyan] {page_url}")
        console.print(
            "[yellow]Will scroll, wait for lazy-load, download each batch, "
            "and skip already-saved reels.[/yellow]"
        )
        page.goto(page_url, wait_until="domcontentloaded")
        page.wait_for_timeout(4000)
        _wait_for_facebook_login(page, context)
        _dismiss_login_walls(page)

        if cookies_out is not None:
            cookie_path = export_cookies(context, cookies_out)

        for scroll_idx in range(max_scrolls):
            if limit is not None and len(all_urls) >= limit:
                break

            batch = _harvest_visible_reels(page, seen)
            if limit is not None:
                remaining = limit - len(all_urls)
                batch = batch[:remaining]

            if batch:
                stagnant = 0
                all_urls.extend(batch)
                console.print(
                    f"  batch @ scroll {scroll_idx}: +{len(batch)} new "
                    f"(total {len(all_urls)})"
                )
                if cookies_out is not None:
                    cookie_path = export_cookies(context, cookies_out)
                if on_batch is not None:
                    on_batch(batch, cookie_path)
            else:
                stagnant += 1
                console.print(
                    f"  scroll {scroll_idx}: no new reels "
                    f"(stagnant {stagnant}/{stagnant_scrolls_to_stop}, total {len(all_urls)})"
                )

            if limit is not None and len(all_urls) >= limit:
                break
            if stagnant >= stagnant_scrolls_to_stop:
                console.print(
                    "[green]No new reels after repeated scrolls — end of reels tab.[/green]"
                )
                break
            if _looks_past_reels(page):
                console.print("[green]Reached non-reels section — stopping.[/green]")
                break

            prev_unique = page.evaluate(
                """() => {
                  const ids = new Set();
                  for (const a of document.querySelectorAll('a[href*="/reel/"]')) {
                    const m = a.href.match(/\\/reel\\/(\\d+)/);
                    if (m) ids.add(m[1]);
                  }
                  return ids.size;
                }"""
            )
            _scroll_and_wait_for_new(
                page,
                previous_unique=int(prev_unique),
                wait_ms=wait_after_scroll_ms,
            )

        if cookies_out is not None:
            cookie_path = export_cookies(context, cookies_out)
        context.close()

    console.print(f"[green]Enumerated {len(all_urls)} Facebook reel URL(s) total.[/green]")
    return all_urls, cookie_path


def collect_facebook_media_urls(
    page_url: str,
    *,
    limit: int = 20,
    user_data_dir: str | Path = ".playwright/facebook-browse-profile",
    headed: bool = True,
    scroll_rounds: int = 15,
    cookies_out: Path | None = None,
) -> tuple[list[str], Path | None]:
    """Backward-compatible wrapper: harvest up to limit with scroll-and-wait."""
    return harvest_facebook_reels(
        page_url,
        limit=limit,
        user_data_dir=user_data_dir,
        headed=headed,
        stagnant_scrolls_to_stop=5,
        max_scrolls=max(scroll_rounds * 3, 40),
        cookies_out=cookies_out,
    )
